def get_random_service():
    """Возвращает случайную категорию и услугу"""
    import random
    category = random.choice(list(SERVICE_CATEGORIES.keys()))
    service = random.choice(SERVICE_CATEGORIES[category])
    return category, service

def generate_post_prompt(post_type="portfolio_case"):
    """Генерирует промпт для Groq API"""
    import random
    
    category, service = get_random_service()
    template = random.choice(POST_TEMPLATES[post_type]["prompts"])
    
    return template.format(service=service)

def generate_vacancy_prompt():
    """Специальный промпт для вакансии"""
    import random
    category, service = get_random_service()
    industry = random.choice(random.choice(list(INDUSTRY_EXAMPLES.values())))
    
    return f"Вакансия: {service} для проекта {industry}. Требуется специалист. Опиши требования, условия, бюджет и сроки. Сделай пост привлекательным для фрилансеров."

